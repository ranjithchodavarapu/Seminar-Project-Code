# NIST Test

def nist_test(samples):
    """
    Evaluate randomness quality using NIST statistical tests.
    :param samples: Randomness samples.
    :return: NIST test results.
    """
    samples = [1 if s >= 0.5 else 0 for s in samples]
    # Convert the list of samples to a NumPy array before passing to run_all_battery
    samples = np.array(samples)
    results = run_all_battery(samples, SP800_22R1A_BATTERY)
    return results

# Shapiro-Wilk Test
def shapiro_wilk_test(samples):
    """
    Evaluate randomness quality using the Shapiro-Wilk test.
    :param samples: Randomness samples.
    :return: Shapiro-Wilk test statistic and p-value.
    """
    stat, p_value = shapiro(samples)
    return stat, p_value

# Certified Robustness Calculation

def certify_robustness(model, test_loader, n_samples, prng, noise_distribution):
    """
    Calculate certified robustness for the entire test dataset.
    :param model: Trained model.
    :param test_loader: Test dataset loader.
    :param n_samples: Number of noise samples.
    :param prng: Random number generator (standard or cryptographic).
    :param noise_distribution: Type of noise distribution ('laplace', 'abs_normal', 'uniform', 'bernoulli').
    :return: Average certified robustness radius.
    """
    radii = []
    for x, _ in test_loader:
        x = x.numpy()
        radius, _ = randomised_smoothing(model, x, n_samples, prng, noise_distribution)
        radii.append(radius)
    return np.mean(radii)

# Evaluation Metrics Computation

def evaluate_model(model, test_loader, prng, noise_distribution, bit_position=None):
    """
    Evaluate model performance and robustness.
    :param model: Trained model.
    :param test_loader: Test dataset loader.
    :param prng: Random number generator (standard or cryptographic).
    :param noise_distribution: Type of noise distribution ('laplace', 'abs_normal', 'uniform', 'bernoulli').
    :param bit_position: Position of the bit to flip (for bit-flipping attack).
    :return: Clean accuracy, certified robustness, and attack success rates.
    """
    # Clean accuracy
    y_true, y_pred = [], []
    for x, y in test_loader:
        x, y = x.to(device), y.to(device)
        output = model(x)
        pred = torch.argmax(output, dim=1)
        y_true.extend(y.cpu().numpy())
        y_pred.extend(pred.cpu().numpy())
    clean_accuracy = accuracy_score(y_true, y_pred)

    # Certified robustness
    n_samples = 2
    certified_robustness = certify_robustness(model, test_loader, n_samples, prng, noise_distribution)

    # Attack success rates
    target_class = 0
    x, _ = next(iter(test_loader))
    x = x[0].numpy()  # here we use the first test sample for the attack
    attack_types = ['positive_kurtosis', 'negative_kurtosis', 'skewness']
    attack_success_rates = {}
    for attack_type in attack_types:
        attack_success_rates[attack_type] = prng_based_attack(model, x, n_samples, prng, attack_type, target_class, bit_position)

    return clean_accuracy, certified_robustness, attack_success_rates

