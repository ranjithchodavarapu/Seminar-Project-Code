def randomised_smoothing(model, x, n_samples, prng, noise_distribution):
    """
    Certify robustness using randomised smoothing with alternative noise distributions.
    :param model: Trained model.
    :param x: Input sample.
    :param n_samples: Number of noise samples.
    :param prng: Random number generator (standard or cryptographic).
    :param noise_distribution: Type of noise distribution ('laplace', 'abs_normal', 'uniform', 'bernoulli').
    :return: Certified robustness radius and predicted class.
    """
    model.eval()
    counts = np.zeros(10)
    # Get the original shape of the input
    original_shape = x.shape
    # Reshape to remove the batch size, if more than 2 dimensions
    # Iterate through each image in the batch
    for i in range(x.shape[0]):
        single_image = x[i]
        if len(single_image.shape) > 2:
            # Reshape the single image to (3, 32, 32)
            single_image = single_image.reshape(single_image.shape[-3], single_image.shape[-2], single_image.shape[-1])

        for _ in range(n_samples):
            if noise_distribution == 'laplace':
                noise = laplace.rvs(loc=0, scale=0.25, size=single_image.shape).astype(np.float32)
            elif noise_distribution == 'abs_normal':
                noise = np.abs(norm.rvs(loc=0, scale=0.25, size=single_image.shape)).astype(np.float32)
            elif noise_distribution == 'uniform':
                noise = uniform.rvs(loc=-0.25, scale=0.5, size=single_image.shape).astype(np.float32)
            elif noise_distribution == 'bernoulli':
                noise = bernoulli.rvs(0.5, size=single_image.shape).astype(np.float32) - 0.5
            else:
                raise ValueError("Invalid noise distribution.")

            noisy_input = single_image + noise
            noisy_input = torch.from_numpy(noisy_input).unsqueeze(0).to(device)
            output = model(noisy_input)
            pred = torch.argmax(output, dim=1).item()
            counts[pred] += 1

    predicted_class = np.argmax(counts)
    p_a = counts[predicted_class] / n_samples
    radius = 0.25 * norm.ppf(p_a)  # we can adjust radius based on noise distribution
    return radius, predicted_class

#PRNG-Based Attack Simulation (Bit-Flipping PRNG Attacker)

def generate_attack_noise(shape, attack_type):
    """
    Generate attack noise with specific statistical properties.
    :param shape: Shape of the noise.
    :param attack_type: Type of attack ('positive_kurtosis', 'negative_kurtosis', 'skewness').
    :return: Attack noise.
    """
    if attack_type == 'positive_kurtosis':
        # High kurtosis (heavy-tailed distribution)
        noise = np.random.standard_t(3, size=shape)
    elif attack_type == 'negative_kurtosis':
        # Low kurtosis (light-tailed distribution)
        noise = np.random.uniform(-1, 1, size=shape)
    elif attack_type == 'skewness':
        # Skewed distribution
        noise = np.random.exponential(1, size=shape) - 1
    else:
        raise ValueError("Invalid attack type.")
    return noise.astype(np.float32)

def bit_flip_attack(prng_state, bit_position):
    """
    Simulate a bit-flipping attack on the PRNG state.
    :param prng_state: Current state of the PRNG.
    :param bit_position: Position of the bit to flip.
    :return: Modified PRNG state.
    """
    prng_state[bit_position // 8] ^= 1 << (bit_position % 8)
    return prng_state

def prng_based_attack(model, x, n_samples, prng, attack_type, target_class, bit_position=None):
    """
    Simulate a PRNG-based adversarial attack with specific statistical properties.
    :param model: Trained model.
    :param x: Input sample.
    :param n_samples: Number of noise samples.
    :param prng: Random number generator (standard or cryptographic).
    :param attack_type: Type of attack ('positive_kurtosis', 'negative_kurtosis', 'skewness').
    :param target_class: Target class for the attack.
    :param bit_position: Position of the bit to flip (for bit-flipping attack).
    :return: Attack success rate.
    """
    success = 0
    for _ in range(n_samples):
        if bit_position is not None:
            # Perform bit-flipping attack
            prng_state = np.random.get_state()[1].copy()
            prng_state = bit_flip_attack(prng_state, bit_position)
            np.random.set_state((np.random.get_state()[0], prng_state, *np.random.get_state()[2:]))

        base_noise = prng.normal(0, 0.25, size=x.shape).astype(np.float32)
        attack_noise = generate_attack_noise(x.shape, attack_type)
        noisy_input = x + base_noise + attack_noise
        noisy_input = torch.from_numpy(noisy_input).unsqueeze(0).to(device)
        output = model(noisy_input)
        pred = torch.argmax(output, dim=1).item()
        if pred == target_class:
            success += 1

    attack_success_rate = success / n_samples
    return attack_success_rate

